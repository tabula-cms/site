// @ts-check
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import sitemap from '@astrojs/sitemap';

// Repository variables `SITE_URL` and `SITE_BASE` are set in CI (see CONTRIBUTING.md).
// The custom domain, once it exists, will set SITE_BASE=/ (and SITE_URL to the domain)
// without a code change.
const site = process.env.SITE_URL ?? 'https://tabula-cms.github.io';
const base = process.env.SITE_BASE ?? '/site';

// @astrojs/sitemap lists the home twice when `base` has no trailing slash: `…/site` (from the page
// list, whose root path is empty) and `…/site/` (from the route list). Starlight adds the integration
// itself only when none is configured, so ours drops the slash-less duplicate.
const slashless = base === '/' ? null : new URL(base, site).href.replace(/\/$/, '');

// The page «Встановити самостійно» was removed (footer-and-audience-pages spec, 2026-11-09): Tabula is a
// service only. Its old address leads to «Ціна й оплата» and is kept out of the sitemap.
// Astro prefixes `base` to the source of a redirect but not to its destination.
const redirects = { '/vstanovyty-samostiino': `${base.replace(/\/$/, '')}/khostynh-i-tsina/` };
const redirected = Object.keys(redirects).map((from) => new URL(`${base.replace(/\/$/, '')}${from}/`, site).href);

const docsDir = fileURLToPath(new URL('./src/content/docs/', import.meta.url));

// The documentation groups below (only the editor guide since the footer-and-audience-pages spec:
// scripts/lib/docs-transform.mjs PUBLISHED_FOLDERS) are generated by `scripts/fetch-docs.mjs` (issue #3)
// into gitignored folders. Each group is only added to the sidebar once its folder has
// actually been imported — otherwise the group would show with no pages under it (an
// autogenerated group with a missing directory still builds, it's just empty and useless).
/** @type {{ label: string; directory: string }[]} */
const docGroups = [
	{ label: 'Посібник редактора', directory: 'editor' },
];

const sidebar = docGroups
	.filter(({ directory }) => existsSync(`${docsDir}${directory}`))
	// NOTE: not the `{ label, autogenerate }` shorthand — @astrojs/starlight 0.42.4 removed
	// support for that form ("Support for autogenerated sidebar groups was removed in
	// Starlight v0.39.0") and errors on it. This `items: [{ autogenerate }]` form is what
	// its own error message recommends.
	.map(({ label, directory }) => ({ label, items: [{ autogenerate: { directory } }] }));

// https://astro.build/config
export default defineConfig({
	site,
	base,
	// Story 80, decision 9 (no framework JS): Starlight turns Astro's link prefetch on (a page.*.js
	// bundle on every page); the product pages must not load it, and the documentation works without it.
	prefetch: false,
	redirects,
	vite: {
		build: {
			// The home's script (the tabs and the assistant's sequence, src/scripts/tabs.js) is inlined into the page
			// whatever its size (Astro's default limit is 4 KB): loaded as a separate file it ran after the first
			// paint, and the panels that it hides were shown (and their fonts fetched) for a moment first.
			// Everything else keeps the default limit.
			assetsInlineLimit: (file) => (/index\.astro_astro_type_script/.test(file) ? true : undefined),
		},
	},
	integrations: [
		sitemap({ filter: (page) => page !== slashless && !redirected.includes(page) }),
		starlight({
			title: 'Tabula',
			// Single locale: the site is Ukrainian. Developer docs (/dev/) are English; their
			// <html lang> comes from a per-page `lang` frontmatter field via src/routeData.ts
			// (Starlight's own locale routing can't do this without an /en/ tree — see
			// CLAUDE.md). No /en/ tree, no locale switcher.
			locales: {
				root: { label: 'Українська', lang: 'uk' },
			},
			routeMiddleware: './src/routeData.ts',
			// Imported pages have no meaningful git history in this repository. "Edit this page"
			// links are set per page by the import script (#3) as an absolute editUrl pointing
			// at tabula-cms/tabula; there is no site-wide editLink.baseUrl (see CLAUDE.md).
			lastUpdated: false,
			// Explicit even though it matches Starlight's own default (issue #5, design pass
			// 3): documents that `public/favicon.svg` is the site's real mark, not the
			// Starlight placeholder it replaced. Starlight prefixes `base` itself when
			// rendering the `<link rel="icon">` tag (see `fileWithBase` in its `utils/head.js`),
			// so this needs no base-handling here — confirmed in a built `dist/index.html`.
			favicon: '/favicon.svg',
			sidebar,
			// The documentation's deep ink-blue accent palette — see CLAUDE.md and src/styles/site.css.
			customCss: ['./src/styles/site.css'],
			components: {
				// Slice S2 of story 80: Starlight is the documentation only. The footer keeps the default
				// edit-link/pagination footer, adds the link back to the product home and the operator line;
				// the wordmark carries the site's mark. The header is Starlight's own (search, theme switch) —
				// no site navigation: the product pages are not linked from here except through the wordmark and the
				// footer link. See src/components/ and CLAUDE.md.
				Footer: './src/components/Footer.astro',
				// No «Редагувати сторінку»: the imported pages still carry an editUrl into tabula-cms/tabula, which
				// is private; the site names no repository (footer-and-audience-pages spec).
				EditLink: './src/components/EditLink.astro',
				SiteTitle: './src/components/SiteTitle.astro',
			},
		}),
	],
});
